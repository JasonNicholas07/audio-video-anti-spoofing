"""## 7.c Feature extraction — mel-spectrogram, fixed-length clips"""

import librosa
import numpy as np

SAMPLE_RATE = 16000
CLIP_DURATION = 3.5          # seconds — pad/truncate every clip to this length
N_MELS = 128
CLIP_SAMPLES = int(SAMPLE_RATE * CLIP_DURATION)

def load_audio_fixed_length(path, sr=SAMPLE_RATE, target_samples=CLIP_SAMPLES):
    y, orig_sr = librosa.load(path, sr=sr)
    if len(y) > target_samples:
        start = np.random.randint(0, len(y) - target_samples + 1)
        y = y[start:start + target_samples]
    else:
        pad = target_samples - len(y)
        y = np.pad(y, (0, pad), mode="constant")
    return y

def audio_to_melspec(y, sr=SAMPLE_RATE, n_mels=N_MELS):
    mel = librosa.feature.melspectrogram(y=y, sr=sr, n_mels=n_mels)
    mel_db = librosa.power_to_db(mel, ref=np.max)
    mel_db = (mel_db - mel_db.min()) / (mel_db.max() - mel_db.min() + 1e-8)
    return mel_db.astype(np.float32)

"""## 8. Dataset, DataLoader, model, training"""

from torch.utils.data import Dataset, DataLoader
import torch

class AudioSpoofDataset(Dataset):
    def __init__(self, df, augment=False):
        self.df = df.reset_index(drop=True)
        self.augment = augment
        self.label_map = {"real": 0, "fake": 1}

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):
        row = self.df.iloc[idx]
        y = load_audio_fixed_length(row["audio_path"])

        if self.augment:
            if np.random.rand() < 0.3:
                y = y * np.random.uniform(0.7, 1.3)
            if np.random.rand() < 0.2:
                noise = np.random.normal(0, 0.005, y.shape).astype(np.float32)
                y = y + noise

        mel = audio_to_melspec(y)
        mel_tensor = torch.tensor(mel).unsqueeze(0)
        label = self.label_map[row["label"]]
        return mel_tensor, label

