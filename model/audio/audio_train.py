def get_audio_predictions(model, loader, device):
    all_preds, all_probs, all_labels = [], [], []
    with torch.no_grad():
        for mels, labels in loader:
            mels = mels.to(device)
            outputs = model(mels)
            probs = torch.softmax(outputs, dim=1)[:, 1]
