def detect_and_crop_face(image_path, margin=0.2, output_size=224):
    img = cv2.imread(image_path)
    if img is None:
        return None
    h, w = img.shape[:2]
    rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
    mp_image = mp.Image(image_format=mp.ImageFormat.SRGB, data=rgb)
    result = detector.detect(mp_image)
    if not result.detections:
        return None
    best = max(result.detections, key=lambda d: d.categories[0].score)
    bbox = best.bounding_box
    x1 = max(0, int(bbox.origin_x - bbox.width * margin))
    y1 = max(0, int(bbox.origin_y - bbox.height * margin))
    x2 = min(w, int(bbox.origin_x + bbox.width * (1 + margin)))
    y2 = min(h, int(bbox.origin_y + bbox.height * (1 + margin)))
    cropped = img[y1:y2, x1:x2]
    if cropped.size == 0:
        return None
    return cv2.resize(cropped, (output_size, output_size))

