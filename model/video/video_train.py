class VideoSequenceDataset(Dataset):
    def __init__(self, manifest_df, transform, max_seq_len=15):
        df = manifest_df.copy()
        parsed = df["image_path"].apply(lambda p: extract_video_id_and_frame(os.path.basename(p)))
        df["video_id"] = parsed.apply(lambda x: x[0])
        df["frame_idx"] = parsed.apply(lambda x: x[1])
        df = df.dropna(subset=["video_id", "frame_idx"])
        self.groups = df.sort_values("frame_idx").groupby("video_id")
        self.video_ids = list(self.groups.groups.keys())
        self.transform = transform
        self.max_seq_len = max_seq_len
        self.label_map = {"real": 0, "fake": 1}

    def __len__(self):
        return len(self.video_ids)

    def __getitem__(self, idx):
        vid = self.video_ids[idx]
        rows = self.groups.get_group(vid).head(self.max_seq_len)
        frames = []
        for _, row in rows.iterrows():
            img = np.array(Image.open(row["image_path"]).convert("RGB"))
            img = self.transform(image=img)["image"]
            frames.append(img)
        seq = torch.stack(frames)
        label = self.label_map[rows.iloc[0]["label"]]
        return seq, seq.shape[0], label

def collate_sequences(batch):
    seqs, lengths, labels = zip(*batch)
    max_len = max(lengths)
    padded = torch.zeros(len(seqs), max_len, *seqs[0].shape[1:])
    for i, s in enumerate(seqs):
        padded[i, :s.shape[0]] = s
    return padded, torch.tensor(lengths), torch.tensor(labels)

