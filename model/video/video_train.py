def extract_frames_consecutive(video_path, source, label, video_id, output_root,
                                  n_consecutive=N_CONSECUTIVE, start_offset_ratio=0.1):
    cap = cv2.VideoCapture(video_path)
    if not cap.isOpened():
        return 0

    total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
    if total_frames <= 0:
        cap.release()
        return 0

    start_frame = int(total_frames * start_offset_ratio)
    start_frame = min(start_frame, max(0, total_frames - n_consecutive))
    cap.set(cv2.CAP_PROP_POS_FRAMES, start_frame)

    dest_dir = os.path.join(output_root, source, label)
    os.makedirs(dest_dir, exist_ok=True)

    saved = 0
    frame_idx = start_frame
    while saved < n_consecutive:
        ret, frame = cap.read()
        if not ret:
            break
        fname = f"{video_id}_f{frame_idx}.jpg"
        cv2.imwrite(os.path.join(dest_dir, fname), frame)
        saved += 1
        frame_idx += 1

    cap.release()
    return saved

